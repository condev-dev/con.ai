export async function POST(req) {
  try {
    const { brand, handle, topic, platforms, niche, creator } = await req.json();

    if (!topic || !topic.trim() || !brand || !brand.trim()) {
      return new Response("نام برند و موضوع الزامی است.", { status: 400 });
    }

    const validPlatforms = Array.isArray(platforms)
      ? platforms.filter((p) => PLATFORM_BLOCKS[p])
      : [];

    if (validPlatforms.length === 0) {
      return new Response("حداقل یک پلتفرم انتخاب کن.", { status: 400 });
    }

    const cleanHandle = normalizeHandle(handle) || normalizeHandle(brand);

    const system = buildSystemPrompt({
      brand: brand.trim(),
      handle: cleanHandle,
      niche: niche || "",
      creator: "con.dev",
      platforms: validPlatforms,
    });

    const result = streamText({
      model: cohere("command-a-03-2025"),
      system,
      prompt: `موضوع و مشخصات کار امروز:\n${topic.trim()}`,
      maxTokens: 3000,
      temperature: 0.85,
    });

    return result.toTextStreamResponse();
  } catch (err) {
    return new Response("خطایی در پردازش درخواست رخ داد.", { status: 500 });
  }
}
