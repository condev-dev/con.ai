import { cohere } from "@ai-sdk/cohere";
import { streamText } from "ai";

export const runtime = "nodejs";

const NUMERALS = ["۱", "۲", "۳", "۴", "۵", "۶"];
const VIDEO_PLATFORMS = ["instagram", "youtube", "aparat", "facebook"];

const PLATFORM_BLOCKS = {
  instagram: (handle) => `اینستاگرام (Instagram Reels):\n- تایتل/هوک روی ویدیو (۳ ثانیه اول): ۳ پیشنهاد تیتر جذاب و درشت.\n- خط اول کپشن (هوک متنی کوتاه): یک تیتر جذاب که قبل از باز شدن کپشن دیده شود.\n- بدنه کپشن: کوتاه، چالش برانگیز، همراه با دعوت به کامنت گذاشتن کلمه کلیدی.\n- هشتگ ها: دقیقاً پنج هشتگ تخصصی.\n(این پلتفرم مرکز قیف فروش است و CTA اش صرفاً دعوت به کامنت است، نه دایرکت.)`,
  youtube: (handle) => `یوتیوب شورتس (YouTube Shorts):\n- عنوان ویدیو (Title): جذاب، هیجانی، همراه با هشتگ shorts# (بدون کلمات فیک مثل دمو).\n- توضیحات و کامنت پین شده: متن کوتاه و هیجانی، با دعوت به دایرکت اینستاگرام (${handle}) برای گرفتن سورس کد.\n- الگوی ثابت انتها.`,
  aparat: (handle) => `آپارات (Aparat Shorts):\n- توضیحات ویدیو: متن هیجانی و متمرکز روی حل چالش و کارایی کار (مناسب سئوی گوگل) + لینک اینستاگرام و دعوت به دایرکت (${handle}) برای سورس کد.\n- الگوی ثابت انتها.`,
  threads: (handle) => `تردز (Threads):\n- متن پست: کوتاه، داستانی و صمیمی درباره چالش یا ساخت این کار + دعوت به دایرکت اینستاگرام (${handle}).\n- الگوی ثابت انتها.`,
  linkedin: (handle) => `لینکدین (LinkedIn):\n- متن پست: خوانا، با فاصله گذاری خطوط (Line Break)، بدون ایموجی، بدون انگلیسی بازی. بیان چالش واقعی کار و نحوه حل آن با لحن یک متخصص واقعی در حوزه کاری برند (نه مقاله علمی، نه شوخی عامیانه).\n- انتهای پست لینکدین فقط و فقط این عبارت بیاید:\nبرای دیدن نمونه کارهای بیشتر یا ارتباط جهت همکاری و سورس کد، دایرکت اینستاگرام پیام بدید: ${handle}`,
  facebook: (handle) => `فیسبوک (Facebook Reels):\n- متن کپشن: کوتاه، جذاب، ۳ تا ۵ هشتگ مرتبط + لینک اینستاگرام (${handle}).\n- الگوی ثابت انتها.`,
};

const PLATFORM_LABELS = {
  instagram: "اینستاگرام",
  youtube: "یوتیوب شورتس",
  aparat: "آپارات",
  threads: "تردز",
  linkedin: "لینکدین",
  facebook: "فیسبوک",
};

const PLATFORM_ORDER = ["instagram", "youtube", "linkedin", "threads", "facebook", "aparat"];

function buildSystemPrompt({ brand, handle, creator, platforms }) {
  const active = PLATFORM_ORDER.filter((p) => platforms.includes(p));
  const hasLinkedin = active.includes("linkedin");
  const hasInstagram = active.includes("instagram");
  const others = active.filter((p) => p !== "linkedin");
  const needsMusic = active.some((p) => VIDEO_PLATFORMS.includes(p));

  const formatSections = active
    .map((id, i) => `📍 ${NUMERALS[i]}. ${PLATFORM_BLOCKS[id](handle)}`)
    .join("\n\n");

  const musicSection = needsMusic
    ? `\n\n🎵 پیشنهاد موزیک ترند پس زمینه:\n۲ تا ۳ پیشنهاد موزیک یا سبک صدای ترند، مناسب حس و حال این ویدیو (فقط اسم آهنگ یا سبک، بدون لینک).`
    : "";

  return `تو یک متخصص رشد شبکه های اجتماعی و برندسازی شخصی هستی که برای برند «${brand}» کار می کنی. وظیفه تو این است که بر اساس ویدیویی که از عملکرد پروژه یا کار این برند توضیح داده می شود، برای پلتفرم های انتخابی کپشن و سناریو بنویسی، و اگر پلتفرم های ویدیویی جزو انتخاب باشند چند پیشنهاد موزیک ترند پس زمینه هم معرفی کنی.\n\nاین ابزار توسط ${creator} طراحی و ساخته شده است؛ اگر جایی لازم شد از خودت یا سازنده‌ات حرف بزنی، همین را بگو.\n\nپلتفرم های انتخابی برای این بار: ${active.map((p) => PLATFORM_LABELS[p]).join("، ")}.\nفقط برای همین پلتفرم ها خروجی بده، هیچ پلتفرم دیگری را اضافه نکن.\n\nقوانین سخت‌گیرانه لحن، نگارش و ساختار (بسیار مهم):\n\n۱. قانون مهم نگارش (حذف مطلق نیم فاصله):\nبه هیچ عنوان در هیچ کلمه ای از نیم فاصله استفاده نکن. متن باید کاملاً مثل تایپ واقعی یک انسان در شبکه های اجتماعی باشد؛ یعنی تمام کلمات ترکیبی یا جمع ها باید با فاصله معمولی نوشته شوند.\nمثال های الزامی: عکس ها به جای عکس‌ها، سورس کد به جای سورس‌کد، زمان بر به جای زمان‌بر، وب اپ به جای وب‌اپ، پروژه ها به جای پروژه‌ها.\n\n۲. لحن طبیعی و واقعی (حذف عبارات فیک هوش مصنوعی):\nبه هیچ عنوان از کلمات کتابی، خشک اداری، مقاله ای یا عبارات فیک هوش مصنوعی مثل دمو، معرفی پروژه، به عنوان یک پروژه، بهره وری، افزایش سرعت پردازش استفاده نکن. متن باید هیجانی، واقعی، صمیمی و خفن باشد؛ مثلاً بالاخره ساختمش یا این ابزار مشکل... رو کلا حل کرد.\n${
    hasLinkedin
      ? `\n۳. قواعد اختصاصی لینکدین (بسیار مهم):\n- تفکیک و خوانایی: پاراگراف های طولانی و پشت سر هم ننویس. متن باید کاملاً خوانا، با فاصله گذاری بین خطوط باشد.\n- لحن متخصص واقعی: لحن یک متخصص واقعی در حوزه کاری برند که از چالش واقعی کار، نحوه حل آن یا منطق پیاده سازی صحبت می کند، نه مقاله علمی و نه شوخی عامیانه.\n- تمیزی متن: صفر ایموجی یا آیکون، صفر کلمات انگلیسی بی مورد یا نوشتن معادل انگلیسی داخل پرانتز. متن کاملاً فارسی روان باشد.\n- تک دعوت به اقدام: انتهای پست لینکدین فقط و فقط یک بار دعوت به ارتباط دایرکت بیاید و الگوی ثابت انتهای پلتفرم های دیگر مطلقاً در لینکدین تکرار نشود.`
      : ""
  }\n${
    others.length > 0
      ? `\n۴. قواعد بقیه پلتفرم های انتخابی (${others.map((p) => PLATFORM_LABELS[p]).join("، ")}):\n- ایموجی ها بسیار محدود، به جا و طبیعی باشد، اصلاً زیاده روی نکن.`
      : ""
  }\n${
    hasInstagram
      ? `\n۵. ساختار کپشن اینستاگرام:\n- خط اول کپشن (قبل از مشاهده بیشتر) باید یک هوک/تیتر کوتاه و ضربتی باشد تا کاربر را بکشاند به باز کردن کپشن.\n- بعد از خط اول، اصل توضیحات کوتاه و کاربردی بیاید.`
      : ""
  }\n\n۶. لحن دعوت به همکاری و سفارش پروژه:\nاز جملات خشک و رسمی استفاده نکن. فقط عبارت های کوتاه، صمیمی و مستقیم به کار ببر (مثل: ایده ای برای همکاری داری؟ دایرکت پیام بده).\n\n۷. استراتژی قیف فروش:\nدر تمام پلتفرم های انتخابی به جز خود اینستاگرام (اگر جزو انتخاب باشد)، هدف اصلی ترغیب مخاطب به رفتن به دایرکت اینستاگرام (${handle}) برای دریافت سورس کد یا سفارش پروژه است. آدرس مستقیم تلگرام در هیچ پلتفرمی نباید قرار گیرد.\n\n۸. قالب بندی خروجی:\nبرای هر پلتفرم انتخابی حتماً نام آن را با نشانه 📍 در ابتدای خط درج کن تا مشخص باشد هر بخش مربوط به کدام پلتفرم است. فقط خروجی نهایی را برگردان، بدون هیچ توضیح اضافه قبل یا بعد از آن.\n\nفرمت خروجی مورد انتظار (دقیقاً به همین ترتیب):\n\n${formatSections}${musicSection}\n\nنام برند یا پیج: ${brand}\nآیدی اینستاگرام برای دایرکت: ${handle}`;
}

export async function POST(req) {
  try {
    const { brand, handle, topic, platforms, creator } = await req.json();

    if (!topic || !topic.trim() || !brand || !brand.trim()) {
      return new Response("نام برند و موضوع الزامی است.", { status: 400 });
    }

    const validPlatforms = Array.isArray(platforms)
      ? platforms.filter((p) => PLATFORM_BLOCKS[p])
      : [];

    if (validPlatforms.length === 0) {
      return new Response("حداقل یک پلتفرم انتخاب کن.", { status: 400 });
    }

    const system = buildSystemPrompt({
      brand: brand.trim(),
      handle: (handle || brand).trim(),
      creator: creator || "Con Dev",
      platforms: validPlatforms,
    });

    const result = streamText({
      model: cohere("command-r-08-2024"),
      system,
      prompt: `موضوع و مشخصات پروژه یا ویدیوی امروز:\n${topic.trim()}`,
      maxTokens: 1700,
      temperature: 0.8,
    });

    return result.toTextStreamResponse();
  } catch (err) {
    return new Response("خطایی در پردازش درخواست رخ داد.", { status: 500 });
  }
}
